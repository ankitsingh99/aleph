#!/bin/sh
# Showcase mode's module, src/lib/showcase.ts (generated, not committed):
# a copy of showcase/stub.ts — inert, what every build ships — or, with
# ALEPH_SHOWCASE=1 (for a demo build of Aleph: cargo --features showcase),
# of showcase/real.ts (the banner, ✦ titles, the menu bar's switch).
#
#   sh scripts/showcase.sh            write it (postinstall, prebuild, predev)
#   sh scripts/showcase.sh --ensure   only when it's missing (test, typecheck, lint)
#   sh scripts/showcase.sh --check    fail unless it's the stub (CI)
set -eu
here=$(cd "$(dirname "$0")/.." && pwd)
out="$here/src/lib/showcase.ts"

gen() {
  echo "// Generated by scripts/showcase.sh from showcase/$1.ts: edit that file, not this one."
  cat "$here/showcase/$1.ts"
}

case "${1:-}" in
  --check)
    if [ -f "$out" ] && gen stub | cmp -s - "$out"; then
      echo "showcase: src/lib/showcase.ts is the stub"
      exit 0
    fi
    echo "showcase: src/lib/showcase.ts isn't the stub (run sh scripts/showcase.sh without ALEPH_SHOWCASE)" >&2
    exit 1
    ;;
  --ensure)
    [ -f "$out" ] && exit 0
    ;;
  "") ;;
  *)
    echo "usage: sh scripts/showcase.sh [--ensure | --check]" >&2
    exit 2
    ;;
esac

which=stub
[ "${ALEPH_SHOWCASE:-}" = 1 ] && which=real
tmp="$out.tmp.$$"
gen "$which" >"$tmp"
# unchanged: left alone (no rebuild for nothing)
if [ -f "$out" ] && cmp -s "$tmp" "$out"; then
  rm -f "$tmp"
else
  mv "$tmp" "$out"
fi
echo "showcase: src/lib/showcase.ts from showcase/$which.ts"
